import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const cssRoot = dirname(fileURLToPath(import.meta.url));

/** @param {string} dir */
function collectPartialPcssFiles(dir) {
    /** @type {string[]} */
    const files = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const fullPath = join(dir, entry.name);
        if (entry.isDirectory()) {
            files.push(...collectPartialPcssFiles(fullPath));
            continue;
        }
        if (!/^_.*\.pcss$/i.test(entry.name)) {
            continue;
        }
        if (entry.name === "_components.pcss" || entry.name === "_index.pcss") {
            continue;
        }
        files.push(fullPath);
    }
    return files;
}

const imports = collectPartialPcssFiles(cssRoot)
    .map((file) => {
        const rel = relative(cssRoot, file).replaceAll("\\", "/");
        return `@import "./${rel}";`;
    })
    .sort((a, b) => a.localeCompare(b, "en"));

const output = ["/* autogenerated by rethemendex.sh */", ...imports, ""].join("\n");
writeFileSync(join(cssRoot, "_components.pcss"), output, "utf8");
